// Writes src/lib/text/fallback-widths.ts: ASCII advance widths (1/1000 em) of each Latin
// bundled family, regular and bold. Used to pick the closest stand-in for an unknown PDF font
// from the widths that font has drawn. Run after changing public/fonts: node scripts/build-width-table.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import fontkit from '@pdf-lib/fontkit'

const FAMILIES = { inter: 'Inter', roboto: 'Roboto', tinos: 'Tinos', 'noto-serif': 'NotoSerif', arimo: 'Arimo', carlito: 'Carlito', cousine: 'Cousine', gelasio: 'Gelasio' }
const CHARS = Array.from({ length: 0x7f - 0x21 }, (_, i) => String.fromCharCode(0x21 + i)).join('')
const table = {}
for (const [id, file] of Object.entries(FAMILIES)) {
  for (const style of ['Regular', 'Bold']) {
    const font = fontkit.create(readFileSync(`public/fonts/${file}-${style}.ttf`))
    const k = 1000 / font.unitsPerEm
    table[`${id}${style === 'Bold' ? ':b' : ''}`] = [...CHARS].map((c) => Math.round(font.glyphForCodePoint(c.codePointAt(0)).advanceWidth * k))
  }
}
const body = Object.entries(table)
  .map(([k, v]) => `  '${k}': [${v.join(',')}],`)
  .join('\n')
writeFileSync(
  'src/lib/text/fallback-widths.ts',
  `// Generated by scripts/build-width-table.mjs — do not edit.\n` +
    `/** Characters U+0021–U+007E, in order. */\nexport const WIDTH_CHARS = ${JSON.stringify(CHARS)}\n` +
    `/** Advance widths in 1/1000 em per family (":b" = bold). */\nexport const FAMILY_WIDTHS: Record<string, number[]> = {\n${body}\n}\n`,
)
console.log('wrote', Object.keys(table).length, 'width rows')
